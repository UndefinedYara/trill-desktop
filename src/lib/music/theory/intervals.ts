export function IntervalBetweenNotes(rootNote: string, targetNote: string) {
  const rootNoteIndex = ChromaticScale.indexOf(rootNote);
  const targetNoteIndex = ChromaticScale.indexOf(targetNote);
  return (targetNoteIndex - rootNoteIndex + 12) % 12;
}
